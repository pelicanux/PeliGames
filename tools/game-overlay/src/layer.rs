// Keep Vulkan entry-point names aligned with the loader ABI.
#![allow(non_snake_case)]
//! Vulkan loader ABI, following Khronos' LoaderLayerInterface/vk_layer.h.
//! The layer forwards unhandled entry points to the next layer, not libvulkan:
//! calling the loader from here would recurse through this same layer.
use crate::render::Render;
use crate::Target;
use ash::{vk, vk::Handle, Device, Instance};
use std::{
    collections::HashMap,
    ffi::{c_char, c_void, CStr},
    sync::{
        atomic::{AtomicU64, Ordering},
        Arc, Mutex, OnceLock,
    },
};
type Gipa = vk::PFN_vkGetInstanceProcAddr;
type Gdpa = vk::PFN_vkGetDeviceProcAddr;
type SetData = unsafe extern "system" fn(vk::Device, *mut c_void) -> vk::Result;
#[repr(C)]
pub struct Negotiation {
    kind: u32,
    next: *mut c_void,
    version: u32,
    gipa: Option<Gipa>,
    gdpa: Option<Gdpa>,
    physical: Option<Gipa>,
}
#[repr(C)]
struct InstanceLink {
    next: *mut InstanceLink,
    gipa: Gipa,
    physical: Option<Gipa>,
}
#[repr(C)]
struct DeviceLink {
    next: *mut DeviceLink,
    gipa: Gipa,
    gdpa: Gdpa,
}
#[repr(C)]
union InstanceUnion {
    link: *mut InstanceLink,
    space: [usize; 2],
}
#[repr(C)]
struct InstanceChain {
    kind: vk::StructureType,
    next: *const c_void,
    function: u32,
    data: InstanceUnion,
}
#[repr(C)]
struct Header {
    kind: vk::StructureType,
    next: *const c_void,
}
#[repr(C)]
union DeviceUnion {
    link: *mut DeviceLink,
    set_data: Option<SetData>,
}
#[repr(C)]
struct DeviceChain {
    kind: vk::StructureType,
    next: *const c_void,
    function: u32,
    data: DeviceUnion,
}
struct InstanceData {
    api: Instance,
    gipa: Gipa,
    physical: Option<Gipa>,
    surfaces: Mutex<HashMap<u64, Target>>,
}
struct Swapchain {
    extent: vk::Extent2D,
    format: vk::Format,
    images: Vec<vk::Image>,
    render: Option<Render>,
    eligible: bool,
    surface: Target,
    last_input_ready: Option<bool>,
}
struct DeviceData {
    api: Device,
    instance: Arc<InstanceData>,
    physical: vk::PhysicalDevice,
    gdpa: Gdpa,
    families: Vec<vk::QueueFamilyProperties>,
    queues: HashMap<u64, u32>,
    swapchains: HashMap<u64, Swapchain>,
}
#[derive(Clone, Copy)]
struct Allocation {
    device: vk::Device,
    allocate: vk::PFN_vkAllocateCommandBuffers,
    set_data: Option<SetData>,
}
static INSTANCES: OnceLock<Mutex<HashMap<usize, Arc<InstanceData>>>> = OnceLock::new();
static DEVICES: OnceLock<Mutex<HashMap<usize, Arc<Mutex<DeviceData>>>>> = OnceLock::new();
static ALLOCATIONS: OnceLock<Mutex<HashMap<usize, Allocation>>> = OnceLock::new();
static PRIMARY: AtomicU64 = AtomicU64::new(0);
pub(crate) fn primary_swapchain(id: u64) -> bool {
    id != 0 && id == PRIMARY.load(Ordering::Acquire)
}
// Registry values for presentation-metadata extensions newer than ash 0.38's
// headers. These are forwarded untouched; no identifiers/timestamps are copied
// or generated by the overlay. See VkSwapchainCreateFlagBitsKHR and VkStructureType.
const PRESENT_ID_2: vk::StructureType = vk::StructureType::from_raw(1_000_479_001);
const PRESENT_TIMINGS: vk::StructureType = vk::StructureType::from_raw(1_000_208_003);
const PRESENTATION_METADATA_FLAGS: u32 = 0x40 | 0x80 | 0x200;
fn instances() -> &'static Mutex<HashMap<usize, Arc<InstanceData>>> {
    INSTANCES.get_or_init(Default::default)
}
fn devices() -> &'static Mutex<HashMap<usize, Arc<Mutex<DeviceData>>>> {
    DEVICES.get_or_init(Default::default)
}
fn allocations() -> &'static Mutex<HashMap<usize, Allocation>> {
    ALLOCATIONS.get_or_init(Default::default)
}
unsafe fn key(raw: u64) -> usize {
    if raw == 0 {
        0
    } else {
        *(raw as *const usize)
    }
}
unsafe fn instance(handle: u64) -> Option<Arc<InstanceData>> {
    instances().lock().ok()?.get(&key(handle)).cloned()
}
unsafe fn device(handle: u64) -> Option<Arc<Mutex<DeviceData>>> {
    devices().lock().ok()?.get(&key(handle)).cloned()
}
unsafe fn function<T: Copy>(p: vk::PFN_vkVoidFunction) -> Option<T> {
    p.map(|f| std::mem::transmute_copy(&f))
}
unsafe fn chain(mut p: *const c_void, kind: vk::StructureType, function: u32) -> *mut c_void {
    for _ in 0..128 {
        if p.is_null() {
            break;
        }
        let node = &*(p as *const Header);
        if node.kind == kind && (*(p as *const InstanceChain)).function == function {
            return p as *mut c_void;
        }
        // Only inspect the common sType/pNext for unrelated extension nodes.
        // `function` above must not be read unless sType matches (short-circuit).
        p = node.next;
    }
    std::ptr::null_mut()
}
fn disable(reason: &str) {
    if let Ok(mut s) = crate::state().lock() {
        s.ready = false;
        s.release();
    }
    crate::x11::suspend_pointer();
    crate::report(reason);
}

fn swapchain_rejection(
    info: &vk::SwapchainCreateInfoKHR<'_>,
    surface: Target,
    image_count: usize,
) -> Option<&'static str> {
    if surface == Target::Unavailable {
        return Some("superfície sem uma rota de entrada compatível");
    }
    if image_count == 0 {
        return Some("não foi possível obter as imagens da swapchain");
    }
    if !info
        .image_usage
        .contains(vk::ImageUsageFlags::COLOR_ATTACHMENT)
    {
        return Some("as imagens não permitem desenhar uma camada de cor");
    }
    if info.image_array_layers != 1 {
        return Some("imagens com múltiplas camadas ainda não são cobertas");
    }
    if info.image_extent.width == 0 || info.image_extent.height == 0 {
        return Some("área de apresentação vazia");
    }
    if !matches!(
        info.present_mode,
        vk::PresentModeKHR::FIFO
            | vk::PresentModeKHR::FIFO_RELAXED
            | vk::PresentModeKHR::MAILBOX
            | vk::PresentModeKHR::IMMEDIATE
    ) {
        return Some("modo de apresentação ainda não coberto");
    }
    // DXVK commonly requests MUTABLE_FORMAT for its UNORM/sRGB views. We
    // create our view with the original swapchain format, so that flag does
    // not change our rendering contract. Protected/device-group images and
    // deferred allocation still need separate handling; never accept all bits.
    let supported =
        vk::SwapchainCreateFlagsKHR::MUTABLE_FORMAT.as_raw() | PRESENTATION_METADATA_FLAGS;
    if info.flags.as_raw() & !supported != 0 {
        return Some("flags de criação da swapchain ainda não cobertas");
    }
    if info.image_color_space != vk::ColorSpaceKHR::SRGB_NONLINEAR {
        return Some("o overlay inicial exige uma superfície SDR");
    }
    if !crate::render::sdr_format(info.image_format) {
        return Some("formato de imagem SDR ainda não suportado");
    }
    None
}

#[no_mangle]
pub unsafe extern "system" fn peliNegotiateLoaderLayerInterfaceVersion(
    n: *mut Negotiation,
) -> vk::Result {
    if n.is_null() || (*n).kind != 1 || (*n).version < 1 {
        return vk::Result::ERROR_INITIALIZATION_FAILED;
    }
    (*n).version = (*n).version.min(2);
    (*n).gipa = Some(vkGetInstanceProcAddr);
    (*n).gdpa = Some(vkGetDeviceProcAddr);
    (*n).physical = if (*n).version == 2 {
        Some(physical_proc)
    } else {
        None
    };
    vk::Result::SUCCESS
}
unsafe extern "system" fn physical_proc(
    i: vk::Instance,
    n: *const c_char,
) -> vk::PFN_vkVoidFunction {
    if !n.is_null() && CStr::from_ptr(n).to_bytes() == b"vkCreateDevice" {
        return Some(std::mem::transmute(vkCreateDevice as *const ()));
    }
    let Some(data) = instance(i.as_raw()) else {
        return None;
    };
    match data.physical {
        Some(f) => f(i, n),
        None => (data.gipa)(i, n),
    }
}
macro_rules! address {
    ($f:ident) => {
        Some(std::mem::transmute($f as *const ()))
    };
}
pub unsafe extern "system" fn vkGetInstanceProcAddr(
    i: vk::Instance,
    n: *const c_char,
) -> vk::PFN_vkVoidFunction {
    if n.is_null() {
        return None;
    }
    match CStr::from_ptr(n).to_bytes() {
        b"vkGetInstanceProcAddr" => return address!(vkGetInstanceProcAddr),
        b"vkGetDeviceProcAddr" => return address!(vkGetDeviceProcAddr),
        b"vkCreateInstance" => return address!(vkCreateInstance),
        _ => {}
    }
    let data = instance(i.as_raw())?;
    let next = (data.gipa)(i, n);
    if next.is_none() {
        return None;
    }
    match CStr::from_ptr(n).to_bytes() {
        b"vkDestroyInstance" => address!(vkDestroyInstance),
        b"vkCreateDevice" => address!(vkCreateDevice),
        b"vkCreateWaylandSurfaceKHR" => address!(vkCreateWaylandSurfaceKHR),
        b"vkCreateXlibSurfaceKHR" => address!(vkCreateXlibSurfaceKHR),
        b"vkDestroySurfaceKHR" => address!(vkDestroySurfaceKHR),
        b"vkDestroyDevice" => address!(vkDestroyDevice),
        b"vkGetDeviceQueue" => address!(vkGetDeviceQueue),
        b"vkGetDeviceQueue2" => address!(vkGetDeviceQueue2),
        b"vkCreateSwapchainKHR" => address!(vkCreateSwapchainKHR),
        b"vkDestroySwapchainKHR" => address!(vkDestroySwapchainKHR),
        b"vkQueuePresentKHR" => address!(vkQueuePresentKHR),
        _ => next,
    }
}
pub unsafe extern "system" fn vkGetDeviceProcAddr(
    d: vk::Device,
    n: *const c_char,
) -> vk::PFN_vkVoidFunction {
    if n.is_null() {
        return None;
    }
    if CStr::from_ptr(n).to_bytes() == b"vkGetDeviceProcAddr" {
        return address!(vkGetDeviceProcAddr);
    }
    let data = device(d.as_raw())?;
    let data = data.lock().ok()?;
    let next = (data.gdpa)(d, n);
    if next.is_none() {
        return None;
    }
    match CStr::from_ptr(n).to_bytes() {
        b"vkDestroyDevice" => address!(vkDestroyDevice),
        b"vkGetDeviceQueue" => address!(vkGetDeviceQueue),
        b"vkGetDeviceQueue2" => address!(vkGetDeviceQueue2),
        b"vkCreateSwapchainKHR" => address!(vkCreateSwapchainKHR),
        b"vkDestroySwapchainKHR" => address!(vkDestroySwapchainKHR),
        b"vkQueuePresentKHR" => address!(vkQueuePresentKHR),
        _ => next,
    }
}
pub unsafe extern "system" fn vkCreateInstance(
    info: *const vk::InstanceCreateInfo<'_>,
    allocator: *const vk::AllocationCallbacks<'_>,
    out: *mut vk::Instance,
) -> vk::Result {
    if info.is_null() || out.is_null() {
        return vk::Result::ERROR_INITIALIZATION_FAILED;
    }
    let link = chain(
        (*info).p_next,
        vk::StructureType::LOADER_INSTANCE_CREATE_INFO,
        0,
    ) as *mut InstanceChain;
    if link.is_null() || (*link).data.link.is_null() {
        return vk::Result::ERROR_INITIALIZATION_FAILED;
    }
    let next = &*(*link).data.link;
    let gipa = next.gipa;
    let physical = next.physical;
    let Some(create) = function::<vk::PFN_vkCreateInstance>(gipa(
        vk::Instance::null(),
        c"vkCreateInstance".as_ptr(),
    )) else {
        return vk::Result::ERROR_INITIALIZATION_FAILED;
    };
    (*link).data.link = next.next;
    let result = create(info, allocator, out);
    if result == vk::Result::SUCCESS {
        let api = Instance::load(
            &ash::StaticFn {
                get_instance_proc_addr: gipa,
            },
            *out,
        );
        if let Ok(mut map) = instances().lock() {
            map.insert(
                key((*out).as_raw()),
                Arc::new(InstanceData {
                    api,
                    gipa,
                    physical,
                    surfaces: Mutex::new(HashMap::new()),
                }),
            );
        }
    }
    result
}
pub unsafe extern "system" fn vkDestroyInstance(
    i: vk::Instance,
    a: *const vk::AllocationCallbacks<'_>,
) {
    crate::wineland::forget(i.as_raw() as usize);
    if let Some(data) = instance(i.as_raw()) {
        if let Ok(mut map) = instances().lock() {
            map.remove(&key(i.as_raw()));
        }
        if let Ok(mut surfaces) = data.surfaces.lock() {
            for (_, target) in surfaces.drain() {
                if let Target::Xlib(window) = target {
                    crate::x11::unregister(window);
                }
            }
        }
        (data.api.fp_v1_0().destroy_instance)(i, a);
    }
}
pub unsafe extern "system" fn vkCreateDevice(
    p: vk::PhysicalDevice,
    info: *const vk::DeviceCreateInfo<'_>,
    a: *const vk::AllocationCallbacks<'_>,
    out: *mut vk::Device,
) -> vk::Result {
    if info.is_null() || out.is_null() {
        return vk::Result::ERROR_INITIALIZATION_FAILED;
    }
    let Some(inst) = instance(p.as_raw()) else {
        return vk::Result::ERROR_INITIALIZATION_FAILED;
    };
    let link = chain(
        (*info).p_next,
        vk::StructureType::LOADER_DEVICE_CREATE_INFO,
        0,
    ) as *mut DeviceChain;
    if link.is_null() || (*link).data.link.is_null() {
        return vk::Result::ERROR_INITIALIZATION_FAILED;
    }
    let callbacks = chain(
        (*info).p_next,
        vk::StructureType::LOADER_DEVICE_CREATE_INFO,
        1,
    ) as *mut DeviceChain;
    let set_data = if callbacks.is_null() {
        None
    } else {
        (*callbacks).data.set_data
    };
    let next = &*(*link).data.link;
    let gipa = next.gipa;
    let gdpa = next.gdpa;
    let Some(create) =
        function::<vk::PFN_vkCreateDevice>(gipa(inst.api.handle(), c"vkCreateDevice".as_ptr()))
    else {
        return vk::Result::ERROR_INITIALIZATION_FAILED;
    };
    (*link).data.link = next.next;
    let result = create(p, info, a, out);
    if result == vk::Result::SUCCESS {
        let handle = *out;
        let Some(allocate) = function::<vk::PFN_vkAllocateCommandBuffers>(gdpa(
            handle,
            c"vkAllocateCommandBuffers".as_ptr(),
        )) else {
            if let Some(destroy) =
                function::<vk::PFN_vkDestroyDevice>(gdpa(handle, c"vkDestroyDevice".as_ptr()))
            {
                destroy(handle, a);
            }
            *out = vk::Device::null();
            return vk::Result::ERROR_INITIALIZATION_FAILED;
        };
        if let Ok(mut map) = allocations().lock() {
            map.insert(
                key(handle.as_raw()),
                Allocation {
                    device: handle,
                    allocate,
                    set_data,
                },
            );
        }
        let api = Device::load_with(
            |name| {
                if name.to_bytes() == b"vkAllocateCommandBuffers" {
                    allocate_commands as *const () as *const c_void
                } else {
                    gdpa(handle, name.as_ptr())
                        .map_or(std::ptr::null(), |f| f as *const () as *const c_void)
                }
            },
            handle,
        );
        let families = inst.api.get_physical_device_queue_family_properties(p);
        let data = DeviceData {
            api,
            instance: inst,
            physical: p,
            gdpa,
            families,
            queues: HashMap::new(),
            swapchains: HashMap::new(),
        };
        if let Ok(mut map) = devices().lock() {
            map.insert(key(handle.as_raw()), Arc::new(Mutex::new(data)));
        }
    }
    result
}
unsafe extern "system" fn allocate_commands(
    d: vk::Device,
    info: *const vk::CommandBufferAllocateInfo<'_>,
    out: *mut vk::CommandBuffer,
) -> vk::Result {
    let data = allocations()
        .lock()
        .ok()
        .and_then(|m| m.get(&key(d.as_raw())).copied());
    let Some(data) = data else {
        return vk::Result::ERROR_INITIALIZATION_FAILED;
    };
    let result = (data.allocate)(d, info, out);
    if result == vk::Result::SUCCESS && !info.is_null() {
        if let Some(set) = data.set_data {
            for j in 0..(*info).command_buffer_count as usize {
                let r = set(data.device, (*out.add(j)).as_raw() as *mut c_void);
                if r != vk::Result::SUCCESS {
                    return r;
                }
            }
        }
    }
    result
}
pub unsafe extern "system" fn vkDestroyDevice(
    d: vk::Device,
    a: *const vk::AllocationCallbacks<'_>,
) {
    if let Some(data) = device(d.as_raw()) {
        if let Ok(mut map) = devices().lock() {
            map.remove(&key(d.as_raw()));
        }
        if let Ok(mut data) = data.lock() {
            for id in data.swapchains.keys() { crate::present_metrics::forget(*id); }
            data.swapchains.clear();
            (data.api.fp_v1_0().destroy_device)(d, a);
        }
        if let Ok(mut map) = allocations().lock() {
            map.remove(&key(d.as_raw()));
        }
        PRIMARY.store(0, Ordering::Release);
        disable("Dispositivo encerrado");
    }
}
pub unsafe extern "system" fn vkGetDeviceQueue(
    d: vk::Device,
    family: u32,
    index: u32,
    out: *mut vk::Queue,
) {
    if let Some(data) = device(d.as_raw()) {
        if let Ok(mut data) = data.lock() {
            (data.api.fp_v1_0().get_device_queue)(d, family, index, out);
            if !out.is_null() {
                data.queues.insert((*out).as_raw(), family);
            }
        }
    }
}
pub unsafe extern "system" fn vkGetDeviceQueue2(
    d: vk::Device,
    info: *const vk::DeviceQueueInfo2<'_>,
    out: *mut vk::Queue,
) {
    if let Some(data) = device(d.as_raw()) {
        if let Ok(mut data) = data.lock() {
            (data.api.fp_v1_1().get_device_queue2)(d, info, out);
            if !info.is_null() && !out.is_null() && (*info).flags.is_empty() {
                data.queues
                    .insert((*out).as_raw(), (*info).queue_family_index);
            }
        }
    }
}
pub unsafe extern "system" fn vkCreateWaylandSurfaceKHR(
    i: vk::Instance,
    info: *const vk::WaylandSurfaceCreateInfoKHR<'_>,
    a: *const vk::AllocationCallbacks<'_>,
    out: *mut vk::SurfaceKHR,
) -> vk::Result {
    let Some(data) = instance(i.as_raw()) else {
        return vk::Result::ERROR_INITIALIZATION_FAILED;
    };
    let Some(f) = function::<vk::PFN_vkCreateWaylandSurfaceKHR>((data.gipa)(
        i,
        c"vkCreateWaylandSurfaceKHR".as_ptr(),
    )) else {
        return vk::Result::ERROR_EXTENSION_NOT_PRESENT;
    };
    let result = f(i, info, a, out);
    if result == vk::Result::SUCCESS && !info.is_null() && !out.is_null() {
        if let Ok(mut map) = data.surfaces.lock() {
            map.insert((*out).as_raw(), Target::Wayland((*info).surface as usize));
        }
    }
    result
}
pub unsafe extern "system" fn vkCreateXlibSurfaceKHR(
    i: vk::Instance,
    info: *const vk::XlibSurfaceCreateInfoKHR<'_>,
    a: *const vk::AllocationCallbacks<'_>,
    out: *mut vk::SurfaceKHR,
) -> vk::Result {
    let Some(data) = instance(i.as_raw()) else {
        return vk::Result::ERROR_INITIALIZATION_FAILED;
    };
    let Some(f) = function::<vk::PFN_vkCreateXlibSurfaceKHR>((data.gipa)(
        i,
        c"vkCreateXlibSurfaceKHR".as_ptr(),
    )) else {
        return vk::Result::ERROR_EXTENSION_NOT_PRESENT;
    };
    let result = f(i, info, a, out);
    if result == vk::Result::SUCCESS && !info.is_null() && !out.is_null() {
        // A successful Wineland v1 registration identifies the real Wayland
        // surface even when this layer sits above its surface translator.
        // Never install Xlib input/grabs on Steam's offscreen proxy window.
        let translated =
            crate::wineland::target(i.as_raw() as usize, (*info).dpy as usize, (*info).window);
        let target = xlib_target(translated, (*info).window, || {
            crate::x11::register((*info).dpy.cast(), (*info).window)
        });
        if let Ok(mut map) = data.surfaces.lock() {
            map.insert((*out).as_raw(), target);
        }
    }
    result
}
fn xlib_target(translated: Option<Target>, window: u64, register: impl FnOnce() -> bool) -> Target {
    if let Some(Target::Wayland(surface)) = translated {
        return Target::Wayland(surface);
    }
    if register() {
        Target::Xlib(window)
    } else {
        Target::Unavailable
    }
}
pub unsafe extern "system" fn vkDestroySurfaceKHR(
    i: vk::Instance,
    s: vk::SurfaceKHR,
    a: *const vk::AllocationCallbacks<'_>,
) {
    if let Some(data) = instance(i.as_raw()) {
        if let Ok(mut map) = data.surfaces.lock() {
            if let Some(Target::Xlib(window)) = map.remove(&s.as_raw()) {
                crate::x11::unregister(window);
            }
        }
        if let Some(f) =
            function::<vk::PFN_vkDestroySurfaceKHR>((data.gipa)(i, c"vkDestroySurfaceKHR".as_ptr()))
        {
            f(i, s, a);
        }
    }
}
pub unsafe extern "system" fn vkCreateSwapchainKHR(
    d: vk::Device,
    info: *const vk::SwapchainCreateInfoKHR<'_>,
    a: *const vk::AllocationCallbacks<'_>,
    out: *mut vk::SwapchainKHR,
) -> vk::Result {
    let Some(data) = device(d.as_raw()) else {
        return vk::Result::ERROR_INITIALIZATION_FAILED;
    };
    let Ok(mut data) = data.lock() else {
        return vk::Result::ERROR_INITIALIZATION_FAILED;
    };
    let Some(f) =
        function::<vk::PFN_vkCreateSwapchainKHR>((data.gdpa)(d, c"vkCreateSwapchainKHR".as_ptr()))
    else {
        return vk::Result::ERROR_EXTENSION_NOT_PRESENT;
    };
    // Do not modify application-owned pNext chains, usage, image counts or
    // presentation policy. Unsupported swapchains remain transparent passthrough.
    let result = f(d, info, a, out);
    if result == vk::Result::SUCCESS && !info.is_null() && !out.is_null() {
        let info = &*info;
        let surface = data
            .instance
            .surfaces
            .lock()
            .ok()
            .and_then(|m| m.get(&info.surface.as_raw()).copied())
            .unwrap_or_default();
        let get = function::<vk::PFN_vkGetSwapchainImagesKHR>((data.gdpa)(
            d,
            c"vkGetSwapchainImagesKHR".as_ptr(),
        ));
        let mut images = Vec::new();
        if let Some(get) = get {
            let mut count = 0;
            if get(d, *out, &mut count, std::ptr::null_mut()) == vk::Result::SUCCESS
                && count <= 64
                && count > 0
            {
                images.resize(count as usize, vk::Image::null());
                if get(d, *out, &mut count, images.as_mut_ptr()) != vk::Result::SUCCESS {
                    images.clear();
                } else {
                    images.truncate(count as usize);
                }
            }
        }
        let rejection = swapchain_rejection(info, surface, images.len());
        crate::report(&format!(
            "Swapchain: {}; superfície={surface:?}; imagens={}; dimensão={}x{}; formato={:?}; flags=0x{:x}; uso=0x{:x}; apresentação={:?}; espaço de cor={:?}",
            rejection.unwrap_or("compatível; aguardando apresentação"),
            images.len(), info.image_extent.width, info.image_extent.height,
            info.image_format, info.flags.as_raw(), info.image_usage.as_raw(),
            info.present_mode, info.image_color_space,
        ));
        data.swapchains.insert(
            (*out).as_raw(),
            Swapchain {
                extent: info.image_extent,
                format: info.image_format,
                images,
                render: None,
                eligible: rejection.is_none(),
                surface,
                last_input_ready: None,
            },
        );
    }
    result
}
pub unsafe extern "system" fn vkDestroySwapchainKHR(
    d: vk::Device,
    s: vk::SwapchainKHR,
    a: *const vk::AllocationCallbacks<'_>,
) {
    crate::present_metrics::forget(s.as_raw());
    if let Some(data) = device(d.as_raw()) {
        if let Ok(mut data) = data.lock() {
            data.swapchains.remove(&s.as_raw());
            if PRIMARY
                .compare_exchange(s.as_raw(), 0, Ordering::AcqRel, Ordering::Acquire)
                .is_ok()
            {
                disable("Swapchain encerrada");
            }
            if let Some(f) = function::<vk::PFN_vkDestroySwapchainKHR>((data.gdpa)(
                d,
                c"vkDestroySwapchainKHR".as_ptr(),
            )) {
                f(d, s, a);
            }
        }
    }
}
pub unsafe extern "system" fn vkQueuePresentKHR(
    q: vk::Queue,
    info: *const vk::PresentInfoKHR<'_>,
) -> vk::Result {
    let result = present_game(q, info);
    if result.as_raw() >= 0 && !info.is_null() && (*info).swapchain_count == 1 && !(*info).p_swapchains.is_null()
        && ((*info).p_results.is_null() || (*(*info).p_results).as_raw() >= 0) {
        let id=(*(*info).p_swapchains).as_raw();
        if primary_swapchain(id) { crate::present_metrics::record(id,crate::present_metrics::renderer_is_source()); }
    }
    result
}
unsafe fn present_game(q:vk::Queue, info:*const vk::PresentInfoKHR<'_>)->vk::Result {
    let Some(data) = device(q.as_raw()) else {
        return vk::Result::ERROR_INITIALIZATION_FAILED;
    };
    let Ok(mut data) = data.lock() else {
        return vk::Result::ERROR_INITIALIZATION_FAILED;
    };
    let Some(next) = function::<vk::PFN_vkQueuePresentKHR>((data.gdpa)(
        data.api.handle(),
        c"vkQueuePresentKHR".as_ptr(),
    )) else {
        return vk::Result::ERROR_EXTENSION_NOT_PRESENT;
    };
    if info.is_null()
        || (*info).swapchain_count != 1
        || (*info).p_swapchains.is_null()
        || (*info).p_image_indices.is_null()
    {
        disable("Batch de apresentação não coberto");
        return next(q, info);
    }
    let id = (*(*info).p_swapchains).as_raw();
    if !safe_present_chain((*info).p_next) {
        if let Some(sc) = data.swapchains.get_mut(&id) {
            sc.eligible = false;
        }
        disable("Extensão de apresentação ainda não coberta pelo protótipo");
        return next(q, info);
    }
    let Some(family) = data.queues.get(&q.as_raw()).copied() else {
        return next(q, info);
    };
    if !data
        .families
        .get(family as usize)
        .is_some_and(|p| p.queue_flags.contains(vk::QueueFlags::GRAPHICS))
    {
        return next(q, info);
    }
    let instance = data.instance.clone();
    let physical = data.physical;
    let api = data.api.clone();
    let Some(sc) = data.swapchains.get_mut(&id) else {
        return next(q, info);
    };
    if !sc.eligible {
        return next(q, info);
    }
    if sc
        .render
        .as_ref()
        .is_some_and(|render| render.family() != family)
        || *(*info).p_image_indices as usize >= sc.images.len()
    {
        sc.eligible = false;
        PRIMARY.store(0, Ordering::Release);
        disable("Fila/imagem de apresentação mudou fora do contrato inicial");
        return next(q, info);
    }
    let primary = PRIMARY.load(Ordering::Acquire);
    if primary != id
        && (primary != 0
            || PRIMARY
                .compare_exchange(0, id, Ordering::AcqRel, Ordering::Acquire)
                .is_err())
    {
        return next(q, info);
    }
    crate::set_target(sc.surface);
    let Some(controller) = crate::controller() else {
        return next(q, info);
    };
    if sc.render.is_none() {
        match Render::new(
            &instance.api,
            physical,
            api,
            sc.format,
            sc.extent,
            &sc.images,
            family,
        ) {
            Ok(render) => {
                sc.render = Some(render);
                crate::report("Renderer preparado; painel inicia oculto.");
            }
            Err(e) => {
                sc.eligible = false;
                PRIMARY.store(0, Ordering::Release);
                disable(&e);
                return next(q, info);
            }
        }
    }
    crate::presented();
    let input_ready = crate::input_available();
    if sc.last_input_ready != Some(input_ready) {
        sc.last_input_ready = Some(input_ready);
        crate::report(if input_ready {
            "Entrada do jogo reconhecida; atalho do overlay disponível com o jogo em foco."
        } else {
            "Aguardando uma rota de entrada compatível; atalho ainda indisponível."
        });
    }
    if let Ok(mut s) = crate::state().lock() {
        s.ready = input_ready;
    }
    let waits = if (*info).wait_semaphore_count == 0 {
        &[][..]
    } else {
        if (*info).p_wait_semaphores.is_null() {
            return next(q, info);
        }
        std::slice::from_raw_parts(
            (*info).p_wait_semaphores,
            (*info).wait_semaphore_count as usize,
        )
    };
    match sc.render.as_mut().unwrap().paint(
        q,
        family,
        *(*info).p_image_indices as usize,
        waits,
        controller,
    ) {
        Ok(Some(semaphore)) => {
            let semaphores = [semaphore];
            let mut replacement = *info;
            replacement.wait_semaphore_count = 1;
            replacement.p_wait_semaphores = semaphores.as_ptr();
            // Preserve pNext, pResults, swapchains and indices verbatim.
            let result = next(q, &replacement);
            if result.as_raw() < 0 {
                sc.eligible = false;
                PRIMARY.store(0, Ordering::Release);
                disable("Apresentação interrompida");
            }
            result
        }
        Ok(None) => next(q, info),
        Err(e) => {
            sc.eligible = false;
            PRIMARY.store(0, Ordering::Release);
            disable(&e);
            // A failed submit must not be followed by another operation waiting
            // on semaphores whose consumption is no longer established.
            if let Some(result) = sc.render.as_ref().and_then(|r| r.failed_submit) {
                result
            } else {
                next(q, info)
            }
        }
    }
}

unsafe fn safe_present_chain(mut p: *const c_void) -> bool {
    for _ in 0..64 {
        if p.is_null() {
            return true;
        }
        let header = &*(p as *const Header);
        if !matches!(
            header.kind,
            vk::StructureType::PRESENT_ID_KHR
                | PRESENT_ID_2
                | PRESENT_TIMINGS
                | vk::StructureType::PRESENT_TIMES_INFO_GOOGLE
                | vk::StructureType::SWAPCHAIN_PRESENT_FENCE_INFO_EXT
                // DXVK uses maintenance1 to switch FIFO/IMMEDIATE per present.
                // Forward the original mode and pNext chain without editing it.
                | vk::StructureType::SWAPCHAIN_PRESENT_MODE_INFO_EXT
        ) {
            return false;
        }
        p = header.next;
    }
    false
}

