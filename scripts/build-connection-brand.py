#!/usr/bin/env python3
"""Embed the existing PeliGames art/font in standalone login-return pages."""
import base64
import json
import xml.etree.ElementTree as ET
from pathlib import Path

root = Path(__file__).resolve().parents[1]
ET.register_namespace('', 'http://www.w3.org/2000/svg')
logo = ET.fromstring((root / 'public/peligames.svg').read_text())
for node in list(logo):
    if node.tag.endswith('metadata'):
        logo.remove(node)

def data_uri(mime, data):
    return 'data:' + mime + ';base64,' + base64.b64encode(data).decode()

font = data_uri('font/ttf', (root / 'public/fonts/jersey-10/Jersey10-Regular.ttf').read_bytes())
art = data_uri('image/svg+xml', ET.tostring(logo))
facets = data_uri('image/svg+xml', (root / 'public/images/button-facets.svg').read_bytes())
license_text = (root / 'public/fonts/jersey-10/OFL.txt').read_text().replace('*/', '* /')
css = f'''/* Generated from the original PeliGames assets; do not edit embedded data.
{license_text}
*/
@font-face {{ font-family: "Jersey 10"; src: url("{font}") format("truetype"); font-weight: 400; font-style: normal; font-display: swap; }}
body {{ background: radial-gradient(ellipse at 50% 15%, #132337 0, #080c15 65%); }}
main {{ position: relative; isolation: isolate; overflow: hidden; border-color: #285a7d; background: linear-gradient(145deg, #151c2be8, #090f1af5); box-shadow: 0 24px 80px #0009, 0 0 32px #169bff12, inset 0 1px 0 #ffffff0c; }}
main::before {{ content: ""; position: absolute; inset: 0; z-index: -1; border-radius: inherit; pointer-events: none; background: url("{facets}") 0 0 / 288px 144px repeat; mask-image: radial-gradient(ellipse 170px 145px at 0 0, #000, transparent 85%), radial-gradient(ellipse 170px 145px at 100% 100%, #000, transparent 85%); opacity: .55; }}
.brand {{ display: flex; align-items: center; justify-content: center; gap: 12px; margin: 0 0 30px; }}
.brand img {{ display: block; width: 68px; height: 68px; object-fit: contain; filter: drop-shadow(0 0 12px #169bff30); }}
.brand-name {{ font-family: "Jersey 10", monospace; font-size: clamp(38px, 8vw, 46px); font-weight: 400; font-synthesis: none; letter-spacing: 0; line-height: 1.1; white-space: nowrap; color: #f1f4fa; }}
.brand .brand-name span {{ color: #169bff; }}
.status:not(.error) {{ color: #89cfff; border-color: #327fb0; background: #102c42; box-shadow: 0 0 20px #169bff12; }}
.service {{ color: #8ccaff; }}
.next {{ border-color: #25445e; }}
'''
markup = f'<div class="brand"><img src="{art}" alt="" width="68" height="68"><div class="brand-name">Peli<span>Games</span></div></div>'
commands = root / 'src-tauri/src/commands'
(commands / 'connection-brand.css').write_text(css)
(commands / 'connection-brand-markup.html').write_text(markup + '\n')
(root / 'tools/discord-auth/src/brand-assets.js').write_text('// Generated by scripts/build-connection-brand.py.\nexport const brandStyles = ' + json.dumps(css, ensure_ascii=False) + ';\nexport const brandMarkup = ' + json.dumps(markup, ensure_ascii=False) + ';\n')
print('Original logo, Jersey 10 font and panel facets embedded in both return pages.')
