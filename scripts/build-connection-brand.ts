#!/usr/bin/env bun
// Embed the existing PeliGames art/font in standalone login-return pages.
// Usage: bun scripts/build-connection-brand.ts
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const read = (path: string) => readFileSync(join(root, path));
const dataUri = (mime: string, data: Buffer | string) => `data:${mime};base64,${Buffer.from(data).toString("base64")}`;

// The logo without editor metadata, comments or the XML declaration.
const logo = read("public/peligames.svg").toString("utf8")
  .replace(/<\?xml[\s\S]*?\?>\s*/g, "")
  .replace(/<!--[\s\S]*?-->/g, "")
  .replace(/<metadata\b[\s\S]*?(<\/metadata>|\/>)/g, "")
  .trim();
const font = dataUri("font/ttf", read("public/fonts/jersey-10/Jersey10-Regular.ttf"));
const art = dataUri("image/svg+xml", logo);
const facets = dataUri("image/svg+xml", read("public/images/button-facets.svg"));
const licenseText = read("public/fonts/jersey-10/OFL.txt").toString("utf8").replaceAll("*/", "* /");
const css = `/* Generated from the original PeliGames assets; do not edit embedded data.
${licenseText}
*/
@font-face { font-family: "Jersey 10"; src: url("${font}") format("truetype"); font-weight: 400; font-style: normal; font-display: swap; }
body { background: radial-gradient(ellipse at 50% 15%, #132337 0, #080c15 65%); }
main { position: relative; isolation: isolate; overflow: hidden; border-color: #285a7d; background: linear-gradient(145deg, #151c2be8, #090f1af5); box-shadow: 0 24px 80px #0009, 0 0 32px #169bff12, inset 0 1px 0 #ffffff0c; }
main::before { content: ""; position: absolute; inset: 0; z-index: -1; border-radius: inherit; pointer-events: none; background: url("${facets}") 0 0 / 288px 144px repeat; mask-image: radial-gradient(ellipse 170px 145px at 0 0, #000, transparent 85%), radial-gradient(ellipse 170px 145px at 100% 100%, #000, transparent 85%); opacity: .55; }
.brand { display: flex; align-items: center; justify-content: center; gap: 12px; margin: 0 0 30px; }
.brand img { display: block; width: 68px; height: 68px; object-fit: contain; filter: drop-shadow(0 0 12px #169bff30); }
.brand-name { font-family: "Jersey 10", monospace; font-size: clamp(38px, 8vw, 46px); font-weight: 400; font-synthesis: none; letter-spacing: 0; line-height: 1.1; white-space: nowrap; color: #f1f4fa; }
.brand .brand-name span { color: #169bff; }
.status:not(.error) { color: #89cfff; border-color: #327fb0; background: #102c42; box-shadow: 0 0 20px #169bff12; }
.service { color: #8ccaff; }
.next { border-color: #25445e; }
`;
const markup = `<div class="brand"><img src="${art}" alt="" width="68" height="68"><div class="brand-name">Peli<span>Games</span></div></div>`;
writeFileSync(join(root, "src-tauri/src/commands/connection-brand.css"), css);
writeFileSync(join(root, "src-tauri/src/commands/connection-brand-markup.html"), markup + "\n");
// The Cloudflare worker stays local (tools/ is not versioned).
try {
  writeFileSync(join(root, "tools/discord-auth/src/brand-assets.js"), `// Generated by scripts/build-connection-brand.ts.\nexport const brandStyles = ${JSON.stringify(css)};\nexport const brandMarkup = ${JSON.stringify(markup)};\n`);
} catch { /* No local worker checkout. */ }
console.log("Original logo, Jersey 10 font and panel facets embedded in both return pages.");
